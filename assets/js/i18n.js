  let currentLang = localStorage.getItem('shuliyuan_lang') || 'zh';

  function t(key) {
    return (dict[currentLang] && dict[currentLang][key]) || (dict.en[key]) || key;
  }

  function applyLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('shuliyuan_lang', lang);
    document.documentElement.setAttribute('lang', lang);

    // 方案1: 替换所有 data-i18n 元素（精确替换）
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
      var el = els[i];
      var key = el.getAttribute('data-i18n');
      if (el.children.length === 0) {
        // 纯文本元素
        el.textContent = t(key);
      }
    }

    // 替换 placeholder
    els = document.querySelectorAll('[data-i18n-placeholder]');
    for (i = 0; i < els.length; i++) {
      els[i].placeholder = t(els[i].getAttribute('data-i18n-placeholder'));
    }

    // 替换 title 属性
    els = document.querySelectorAll('[data-i18n-title]');
    for (i = 0; i < els.length; i++) {
      els[i].title = t(els[i].getAttribute('data-i18n-title'));
    }

    // 替换 alt 属性
    els = document.querySelectorAll('[data-i18n-alt]');
    for (i = 0; i < els.length; i++) {
      els[i].alt = t(els[i].getAttribute('data-i18n-alt'));
    }

    // 替换 content 属性（meta 标签等）
    els = document.querySelectorAll('[data-i18n-content]');
    for (i = 0; i < els.length; i++) {
      els[i].content = t(els[i].getAttribute('data-i18n-content'));
    }

    // 替换 innerHTML（支持包含 HTML 标签的翻译内容）
    els = document.querySelectorAll('[data-i18n-html]');
    for (i = 0; i < els.length; i++) {
      els[i].innerHTML = t(els[i].getAttribute('data-i18n-html'));
    }

    // 替换下拉选项
    els = document.querySelectorAll('[data-i18n-options]');
    for (i = 0; i < els.length; i++) {
      var select = els[i];
      for (var j = 0; j < select.options.length; j++) {
        var optKey = select.options[j].getAttribute('data-i18n-key');
        if (optKey) {
          select.options[j].textContent = t(optKey);
        }
      }
    }

    // 方案2: 全局文本节点遍历替换（兜底，处理未被 data-i18n 覆盖的文本）
    walkTextNodes(document.body);

    // 更新语言切换器文本
    updateLangSwitcher();

    // 触发自定义事件
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));
  }

  // 建立反向查找映射（中文 → 英文 key）
  function buildReverseMap() {
    var map = {};
    var sourceKeys = Object.keys(dict.zh);
    for (var i = 0; i < sourceKeys.length; i++) {
      var k = sourceKeys[i];
      var zhVal = dict.zh[k];
      if (zhVal && typeof zhVal === 'string' && zhVal.length > 0) {
        map[zhVal] = k;
      }
    }
    return map;
  }

